# 다양한 연산자
# + 더하기
# - 빼기
# / 나누기
# // 몫
# * 곱하기
# ** 거듭제곱
# = 같다,대입
# == 똑같다(객체가)
# != 같지않다
# >,< 크다 , 작다
# >= , <= 크거나 같다 , 작거나같다

winner = 50

if winner == 5:
    print("same")
elif winner != 5:
    print("not same")
elif winner > 30:
    print("big win")
elif winner < 30:
    print("smaller win")
else :
    print("done")
